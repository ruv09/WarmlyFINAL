/**
 * Длительности и кривые анимации. Централизовано по той же причине,
 * что и остальные токены: без этого разные экраны неизбежно получают
 * анимации разной "скорости" на глаз — 200ms в одном месте, 300ms
 * в другом, без единого решения, просто потому что так написалось.
 *
 * Значения — миллисекунды, кривые — контрольные точки кубического
 * Безье (формат, который принимает и Animated.Easing.bezier из
 * React Native, и react-native-reanimated). Сознательно не завязано
 * на конкретную анимационную библиотеку — какая именно будет
 * использоваться, решится на этапе реализации компонентов;
 * токены-данные от этого выбора не зависят.
 */
export const DURATIONS = {
  /** Мгновенная обратная связь: нажатие кнопки, переключатель. */
  instant: 100,
  /** Стандартный переход: появление/исчезновение карточки, фейд. */
  fast: 150,
  /** Переход экрана, раскрытие блока. */
  base: 250,
  /** Заметные, "созерцательные" анимации — рост дерева, смена дня. */
  slow: 400,
} as const;

export type DurationToken = keyof typeof DURATIONS;

/** Контрольные точки кубического Безье [x1, y1, x2, y2]. */
export const EASING_CURVES = {
  /** Стандартная кривая Material для большинства переходов. */
  standard: [0.4, 0.0, 0.2, 1] as const,
  /** Вход элемента на экран: быстрый старт, плавное замедление. */
  decelerate: [0.0, 0.0, 0.2, 1] as const,
  /** Уход элемента с экрана: плавный старт, быстрое ускорение. */
  accelerate: [0.4, 0.0, 1, 1] as const,
} as const;

export type EasingToken = keyof typeof EASING_CURVES;

/**
 * Параметры Animated.spring. "soft" — единственный профиль пружины
 * в приложении: без "дребезжания" и заметного перелёта — этого
 * требует принцип "avoid flashy effects". Дополнительные профили
 * (например, более энергичный) добавляются сюда же по мере
 * необходимости, а не изобретаются заново в компоненте.
 */
export const SPRING_CONFIGS = {
  soft: { damping: 18, stiffness: 120, mass: 1 },
} as const;

export type SpringConfigToken = keyof typeof SPRING_CONFIGS;

/**
 * Приложение позиционируется как спокойное и ненавязчивое — поэтому,
 * когда анимации будут реализованы, компоненты обязаны проверять
 * системную настройку "уменьшить анимацию" (AccessibilityInfo.
 * isReduceMotionEnabled на RN) и по возможности заменять анимацию
 * на мгновенный переход (DURATIONS.instant или без анимации вовсе),
 * а не просто ускорять её. Сейчас это зафиксировано как требование
 * к будущей реализации, а не код — компонентов, использующих
 * анимацию, в проекте пока нет.
 */
